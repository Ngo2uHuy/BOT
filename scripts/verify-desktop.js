import assert from 'node:assert/strict';
import {mkdir,mkdtemp,readFile,access} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import {_electron as electron} from 'playwright';
import {Store} from '../src/store.js';
const require=createRequire(import.meta.url);
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const testRoot=path.join(root,'.desktop-test');await mkdir(testRoot,{recursive:true});
const workspace=await mkdtemp(path.join(testRoot,'run-'));
await mkdir(path.join(workspace,'data'));
const store=new Store(path.join(workspace,'data','monitor.sqlite'));
store.ensureUser(1,1);
const source=store.addJoinedGroup(1,{url:'https://www.facebook.com/groups/desktopfixture',name:'Cộng đồng đồ gia dụng · kiểm thử'}).group;
const profile=store.addProfile(1,'https://www.facebook.com/desktopfixture','all').group;
store.observe(source,['101','102'].map(id=>({id,url:`https://www.facebook.com/groups/desktopfixture/posts/${id}`,text:`Bài viết kiểm thử giao diện ${id} — tìm đồ gia dụng cho căn bếp nhỏ.`,publishedAt:new Date().toISOString()})),{render:()=> 'Fixture',matches:()=>true,metricWindowMs:86400000});
store.close();
const env={...process.env,DESKTOP_NODE:process.execPath,DESKTOP_WORKSPACE:workspace,DESKTOP_USER_DATA:path.join(workspace,'electron-profile')};
delete env.ELECTRON_RUN_AS_NODE;
for(const key of Object.keys(env))if(/^(?:TELEGRAM_|ALLOWED_TELEGRAM_|SHOPEE_AFFILIATE_|TIKTOK_AFFILIATE_|DATA_DIR$)/.test(key))delete env[key];
const packaged=process.argv.includes('--packaged');
const executablePath=packaged?path.join(root,'dist','AffiliateDesk-win32-x64','AffiliateDesk.exe'):require('electron');
const application=await electron.launch({executablePath,args:packaged?[]:[path.join(root,'desktop','main.cjs')],env,timeout:60000});
const errors=[];
try {
  const page=await application.firstWindow();
  page.on('pageerror',error=>errors.push(error.message));
  await page.waitForFunction(()=>document.querySelector('#main h1')?.textContent.includes('Mọi hoạt động'),{timeout:30000});
  const snapshot=await page.evaluate(()=>window.desktop.call('bootstrap'));
  assert.equal(snapshot.runtime.running,false);assert.equal(snapshot.stats.groups,2);
  assert.equal(await page.evaluate(()=>typeof window.require),'undefined');
  assert.equal(await page.evaluate(async()=>{try{await window.desktop.call('not-allowed');return false;}catch{return true;}}),true);
  assert.equal(await page.evaluate(async()=>{try{await window.desktop.call('openExternal',{url:'javascript:alert(1)'});return false;}catch{return true;}}),true);
  await page.screenshot({path:path.join(testRoot,packaged?'desktop-packaged.png':'desktop-dashboard.png'),fullPage:true});
  await page.locator('#navigation [data-page="sources"]').click();
  await page.locator('[data-action="add-source"]').first().click();
  await page.locator('#add-source-form textarea[name="urls"]').fill('https://www.facebook.com/groups/desktopsecond');
  await page.locator('#add-source-form button[type="submit"]').click();
  await page.waitForFunction(async()=> (await window.desktop.call('bootstrap')).sources.length===3);
  if(await page.locator('#modal').evaluate(node=>node.open))await page.locator('#modal [data-action="close-modal"]').first().click();
  await page.locator('#navigation [data-page="posts"]').click();
  await page.getByText('Bài viết kiểm thử giao diện', {exact:false}).first().waitFor();
  await page.screenshot({path:path.join(testRoot,'desktop-posts.png'),fullPage:true});
  await page.getByRole('checkbox',{name:'Chọn bài 101',exact:true}).check();
  await page.getByRole('checkbox',{name:'Chọn bài 102',exact:true}).check();
  await page.locator('[data-action="selected-comment"]').click();
  await page.locator('#comment-form textarea[name="comments"]').fill('https://s.shopee.vn/test-one\nhttps://vt.tiktok.com/test-two');
  await page.locator('#comment-form button[type="submit"]').click();
  await page.waitForFunction(async()=> (await window.desktop.call('comments',{ownerId:1})).items.length===4);
  await page.locator('#modal [data-action="close-modal"]').first().click();
  const queued=await page.evaluate(()=>window.desktop.call('comments',{ownerId:1}));
  assert.equal(queued.items.length,4);assert.ok(queued.items.every(item=>item.state==='pending'));
  await page.locator('#navigation [data-page="affiliate"]').click();
  await page.locator('#main h1').waitFor();
  await page.screenshot({path:path.join(testRoot,'desktop-affiliate.png'),fullPage:true});
  await page.locator('#navigation [data-page="settings"]').click();
  await page.locator('#settings-form').waitFor();
  await page.screenshot({path:path.join(testRoot,'desktop-settings.png'),fullPage:true});
  await page.evaluate(({groupId})=>window.desktop.call('command',{ownerId:1,text:`/cancelcomments ${groupId}`}),{groupId:source.id});
  await page.locator('#settings-form input[name="ALLOWED_TELEGRAM_USER_IDS"]').fill('2');
  await page.locator('#settings-form button[type="submit"]').click();
  await page.waitForFunction(()=>document.querySelector('#owner-select')?.value==='2');
  const switched=await page.evaluate(()=>window.desktop.call('bootstrap'));
  assert.equal(switched.ownerId,2);assert.equal(switched.sources.length,0);
  assert.equal(switched.runtime.running,false);
  await page.setViewportSize({width:1000,height:760});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'No horizontal overflow at minimum window width');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({packaged,checks:'Window, IPC isolation, source form, posts, queued comments (no send), affiliate/settings rendering',workspace,screenshots:testRoot}));
} finally {await application.close();}
// Shutdown must release the shared runtime lock, including when jobs are pending.
let locked=true;
for(let i=0;i<30;i++) {try{await access(path.join(workspace,'data','monitor.lock'));await new Promise(r=>setTimeout(r,100));}catch{locked=false;break;}}
assert.equal(locked,false,'Desktop must release monitor.lock on quit');
